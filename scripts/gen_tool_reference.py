#!/usr/bin/env python3
"""Generate docs/TOOLS-ARGUMENTS.md (every MCP tool with its arguments, one section per toolset) and the
count blocks other pages carry, all from the code.

Catalogued tools come from the packaged snapshots (``mcp/twinsmith/catalogs/*.json``); host tools
come from their function signatures, read with ``ast`` so this needs no dependencies, no bridge
and no simulator. ``scripts/check_docs.py`` fails when the page has drifted.

    python3 scripts/gen_tool_reference.py --write   # regenerate the page and the count blocks
    python3 scripts/gen_tool_reference.py --check   # exit 1 when any has drifted (default)

A page that shows how many tools a toolset or profile lists wraps the figures in a block,
``<!-- generated:toolsets-compact -->`` ... ``<!-- /generated -->``, so the numbers are never typed by
hand. The block names are ``toolsets-compact``, ``toolsets-full`` and ``profiles``.
"""

import argparse
import ast
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "mcp"))
from twinsmith import tool_groups, toolsets  # noqa: E402 - stdlib-only data
OUTPUT = ROOT / "docs" / "TOOLS-ARGUMENTS.md"
CATALOGS = ROOT / "mcp" / "twinsmith" / "catalogs"
HEADER = """# Tool arguments

**Generated by `scripts/gen_tool_reference.py`; do not edit by hand.** Every tool the server
registers, with its arguments, taken from the code and grouped by [toolset](TOOLSETS.md). Use it to look
up a name, a default or what is required. For behavior, refusals and limits, read the page linked in
each section.

A client is shown most of these as an action of a grouped tool: each toolset section lists its listed
tools with their actions, and each single-purpose tool says "Listed as". Both take the same arguments.
The single-purpose name still works when called while its toolset is enabled. A toolset that is off
registers no tools.

Arguments are shown as `name` (type, required) or `name` (type, default). Generic scene tools refuse
arguments they do not declare, so a misspelled name is an error rather than being ignored. A live
bridge's own metadata takes precedence over these snapshots once discovered.
"""
LOCAL_MODULES = ("server.py", "screen.py", "desktop_input.py", "sim_sessions.py", "isaaclab/tools.py",
                 "robosim/tools.py", "sysid.py", "hardware.py", "gap.py", "vabar.py")
CATALOGS_BY_NAME = ("builtins.json", "sim.json", "assets.json", "workcell.json")
# Where each toolset's behaviour is described, relative to docs/.
REFERENCE = {
    "core": "TOOLS-HOST.md", "computer": "TOOLS-HOST.md#computer", "sim": "TOOLS-SCENE.md",
    "assets": "ASSET-IMPORT.md", "cad": "HARDWARE.md", "real2sim": "ROBOSIM.md",
    "planning": "PLANNING-EVAL.md#gap", "eval": "PLANNING-EVAL.md#vabar",
}


def one_line(text):
    return " ".join((text or "").split())


def annotated_parts(annotation, aliases):
    """Return (type source, description) of a signature annotation, seeing through Annotated.

    The module-level alias form (``_WindowId = Annotated[...]``) counts as well. Only the source is
    read, so this stays free of pydantic and of the SDK.
    """
    if isinstance(annotation, ast.Name) and annotation.id in aliases:
        annotation = aliases[annotation.id]
    if not (isinstance(annotation, ast.Subscript) and isinstance(annotation.value, ast.Name)
            and annotation.value.id == "Annotated" and isinstance(annotation.slice, ast.Tuple)):
        return ast.unparse(annotation), ""
    base, *metadata = annotation.slice.elts
    for item in metadata:
        if isinstance(item, ast.Call) and getattr(item.func, "id", "") == "Field":
            for keyword in item.keywords:
                if keyword.arg == "description" and isinstance(keyword.value, ast.Constant):
                    return ast.unparse(base), keyword.value.value
    return ast.unparse(base), ""


def local_tools(path):
    """Return {tool name: (description, [(arg, type, required, default, detail)])} for one host module."""
    tools = {}
    tree = ast.parse(path.read_text())
    aliases = {target.id: node.value for node in tree.body if isinstance(node, ast.Assign)
               and isinstance(node.value, ast.Subscript)
               for target in node.targets if isinstance(target, ast.Name)}
    # A default such as DEFAULT_MAX_WIDTH reads better, and matches the MCP schema, as its value.
    constants = {target.id: node.value for node in tree.body if isinstance(node, ast.Assign)
                 and isinstance(node.value, ast.Constant)
                 for target in node.targets if isinstance(target, ast.Name)}
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        decorators = [d for d in node.decorator_list if isinstance(d, ast.Call)
                      and isinstance(d.func, ast.Attribute) and d.func.attr == "tool"]
        if not decorators:
            continue
        name = next((kw.value.value for kw in decorators[0].keywords
                     if kw.arg == "name" and isinstance(kw.value, ast.Constant)), node.name)
        positional = node.args.posonlyargs + node.args.args
        defaults = [None] * (len(positional) - len(node.args.defaults)) + list(node.args.defaults)
        arguments = []
        for arg, default in zip(positional + node.args.kwonlyargs,
                                defaults + list(node.args.kw_defaults)):
            if arg.arg in ("self", "ctx"):
                continue
            kind, detail = annotated_parts(arg.annotation, aliases) if arg.annotation is not None else ("any", "")
            if isinstance(default, ast.Name):
                default = constants.get(default.id, default)
            arguments.append((arg.arg, kind, default is None,
                              None if default is None else ast.unparse(default), one_line(detail)))
        doc = ast.get_docstring(node) or ""
        tools[name] = (one_line(doc.split("\n\n", 1)[0]), arguments)
    return tools


def catalog_tools(path):
    tools = {}
    for name, entry in json.loads(path.read_text())["tools"].items():
        arguments = []
        for field in entry.get("fields", []):
            kind = "|".join(field["enum"]) if field.get("enum") else field.get("kind", "any")
            default = json.dumps(field.get("default")) if field.get("has_default") else None
            arguments.append((field["name"], kind, bool(field.get("required")), default,
                              one_line(field.get("description"))))
        tools[name.replace(".", "__")] = (one_line(entry.get("description")), arguments)
    return tools


def render_tool(name, description, arguments):
    lines = [f"### `{name}`", ""]
    listed_as = tool_groups.replacement(name)
    if listed_as:
        lines += [f"Listed as `{listed_as}`.", ""]
    if description:
        lines += [description, ""]
    if not arguments:
        lines += ["No arguments.", ""]
        return lines
    for argument in arguments:
        arg, kind, required, default = argument[:4]
        detail = argument[4] if len(argument) > 4 else ""
        state = "required" if required else ("optional" if default is None else f"default `{default}`")
        lines.append(f"- `{arg}` ({kind}, {state})" + (f": {detail}" if detail else ""))
    lines.append("")
    return lines


def all_tools():
    """{tool name: (description, arguments)} for every registered tool."""
    tools = {}
    for module in LOCAL_MODULES:
        tools.update(local_tools(ROOT / "mcp" / "twinsmith" / module))
    for filename in CATALOGS_BY_NAME:
        tools.update(catalog_tools(CATALOGS / filename))
    return tools


def registered_names():
    """Every registered single-purpose tool name, and every grouped tool's listed name."""
    return set(all_tools()) | set(tool_groups.GROUPS)


def listed_by_toolset():
    """{toolset: [the tools a client is shown for it]}, in toolset order."""
    result = {name: [] for name in toolsets.TOOLSETS}
    for name in tool_groups.listed(set(all_tools())):
        result[toolsets.owner(name)].append(name)
    return result


def _actions(name):
    group = tool_groups.GROUPS.get(name)
    return f"`{name}` ({', '.join(group[1])})" if group else f"`{name}`"


def render():
    tools = all_tools()
    by_toolset = {name: {} for name in toolsets.TOOLSETS}
    for name, entry in tools.items():
        by_toolset[toolsets.owner(name)][name] = entry
    listed = listed_by_toolset()
    lines = [HEADER]
    for toolset, members in by_toolset.items():
        if not members:
            continue
        spec = toolsets.TOOLSETS[toolset]
        state = ("on by default" if spec.default else
                 f"off until you select it with `+{toolset}`" + (" (never enabled by `all`)" if spec.explicit_only else ""))
        link = REFERENCE[toolset]
        lines += [f"<a id=\"{toolset}\"></a>", "", f"## `{toolset}`: {spec.summary}", "",
                  f"Toolset `{toolset}` is {state}. Reference: [{link.split('#')[0].split('/')[-1]}]({link}). "
                  f"{len(members)} tools, listed as {len(listed[toolset])}: "
                  + ", ".join(_actions(name) for name in listed[toolset]) + ".", ""]
        for name in sorted(members):
            lines += render_tool(name, *members[name])
    return "\n".join(lines).rstrip() + "\n"


def _listed_count(toolset_names):
    listed = listed_by_toolset()
    return sum(len(listed[name]) for name in toolset_names)


def render_toolsets_compact():
    listed = listed_by_toolset()
    rows = ["| Toolset | Default | Tools | What it holds |", "|---|---|--:|---|"]
    for name, spec in toolsets.TOOLSETS.items():
        default = "explicit only" if spec.explicit_only else ("on" if spec.default else "off")
        rows.append(f"| `{name}` | {default} | {len(listed[name])} | {spec.summary} |")
    return "\n".join(rows)


def render_toolsets_full():
    listed = listed_by_toolset()
    rows = ["| Group | Default | What it holds | Listed tools |", "|---|---|---|---|"]
    for name, spec in toolsets.TOOLSETS.items():
        default = "explicit only" if spec.explicit_only else ("always on" if spec.default else "off")
        names = ", ".join(f"`{tool}`" for tool in listed[name]) or "none"
        rows.append(f"| **`{name}`** | {default} | {spec.summary} | {names} |")
    return "\n".join(rows)


def render_profiles():
    rows = ["| Profile | Toolsets | Listed tools |", "|---|---|--:|"]
    extra = frozenset(toolsets.PROFILES["all"] | set(toolsets.explicit_only()))
    for label, names in (("`default`", toolsets.PROFILES["default"]), ("`all`", toolsets.PROFILES["all"]),
                         ("`all,+computer`", extra)):
        shown = ", ".join(f"`{n}`" for n in toolsets.TOOLSETS if n in names)
        rows.append(f"| {label} | {shown} | {_listed_count(names)} |")
    return "\n".join(rows)


BLOCKS = {"toolsets-compact": render_toolsets_compact, "toolsets-full": render_toolsets_full,
          "profiles": render_profiles}
BLOCK = re.compile(r"(<!-- generated:([a-z-]+) -->\n)(.*?)(\n?<!-- /generated -->)", re.S)


def refresh_blocks(text):
    """Return text with every generated block rewritten from the code."""
    def fill(match):
        return match.group(1) + BLOCKS[match.group(2)]() + "\n<!-- /generated -->"
    return BLOCK.sub(fill, text)


def block_files():
    """Tracked Markdown files that carry at least one generated block."""
    found = []
    for path in sorted(ROOT.rglob("*.md")):
        if any(part in {".git", ".venv", "node_modules"} for part in path.parts):
            continue
        if "<!-- generated:" in path.read_text(encoding="utf-8"):
            found.append(path)
    return found


def _shown(path):
    try:
        return str(Path(path).relative_to(ROOT))
    except ValueError:
        return str(path)


def stale_pages(output=None, files=None):
    """The pages whose generated content differs from the code."""
    output = OUTPUT if output is None else output
    stale = []
    if not output.is_file() or output.read_text() != render():
        stale.append(_shown(output))
    for path in block_files() if files is None else files:
        current = path.read_text(encoding="utf-8")
        if refresh_blocks(current) != current:
            stale.append(_shown(path))
    return stale


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="regenerate the page and the count blocks")
    group.add_argument("--check", action="store_true", help="exit 1 when any has drifted")
    args = parser.parse_args()
    if args.write:
        OUTPUT.write_text(render())
        print(f"wrote {_shown(OUTPUT)}")
        for path in block_files():
            current = path.read_text(encoding="utf-8")
            if refresh_blocks(current) != current:
                path.write_text(refresh_blocks(current), encoding="utf-8")
                print(f"updated {_shown(path)}")
        return 0
    stale = stale_pages()
    if stale:
        print("stale: " + ", ".join(stale) + ". Run python3 scripts/gen_tool_reference.py --write")
        return 1
    print(f"{_shown(OUTPUT)} and the generated count blocks are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
